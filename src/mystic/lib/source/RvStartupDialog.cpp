rv::StartupDialog::StartupDialog(QString& aRecordingFile, QWidget* aParent, Qt::WindowFlags aFlags /*= Qt::WindowFlags()*/)
   : wkf::StartupDialog<QString>(aRecordingFile, aParent, aFlags)
{
   // 二次开发（i18n）：文档链接显示文本接入翻译通道（链接目标为协议键，保持原样不译）
   mDocLinks = {{QStringLiteral("mystic.html"), QCoreApplication::translate("rv::StartupDialog", "Main Page")},
                {QStringLiteral("mystic_users_guide.html"), QCoreApplication::translate("rv::StartupDialog", "User's Guide")},
                {QStringLiteral("mystic_reference_guide.html"), QCoreApplication::translate("rv::StartupDialog", "Reference Guide")},
                {QStringLiteral("mystic_change_log.html"), QCoreApplication::translate("rv::StartupDialog", "Change Log")},
                {QStringLiteral("event_pipe.html"), QCoreApplication::translate("rv::StartupDialog", "Event Pipe")},
                {QStringLiteral("main_page.html"), QCoreApplication::translate("rv::StartupDialog", "AFSIM Main Page")}};
}

QString rv::StartupDialog::Browse()
{
   // If we have a previous recording, open the Browse Recording dialog to the same directory that recording is in.
   QString directory = RunManager::GetInstance().GetMostRecentDirectory();

   return QFileDialog::getOpenFileName(this,
                                       QCoreApplication::translate("rv::StartupDialog", "Select Recording File"), // 二次开发（i18n）：接入翻译通道
                                       directory,
                                       "AFSIM Event Recording (*.aer);;"); // 二次开发（i18n）：文件类型过滤器含协议通配符，保持原样
}

void rv::StartupDialog::RemoveRecent(const QString& aRecent)
{
   RunManager::GetInstance().RemoveRecentRecording(aRecent);
}

void rv::StartupDialog::ClearRecents()
{
   RunManager::GetInstance().ClearRecentRecordings();
}

const QList<QString>& rv::StartupDialog::GetRecents() const
{
   return RunManager::GetInstance().GetRecentRecordings();
}

QString rv::StartupDialog::GetRecentLabelDisplayName(const QString& aFile, bool aDisplayFullPath) const
{
   return RunManager::GetInstance().GetRecordingDisplayName(aFile, aDisplayFullPath);
}

void rv::StartupDialog::PopulateLabels()
{
   // 二次开发（i18n）：启动对话框各标签接入翻译通道（原为硬编码英文覆盖基类标签）
   mUi.recentsGroupBox->setTitle(QCoreApplication::translate("rv::StartupDialog", "Recent Recordings"));
   mUi.newGroupBox->setTitle(QCoreApplication::translate("rv::StartupDialog", "New Recording"));
   mUi.filesLineEdit->setPlaceholderText(QCoreApplication::translate("rv::StartupDialog", "Drag and drop or enter recording file..."));
   mUi.appDesc->setText(QCoreApplication::translate("rv::StartupDialog", "<p style=\"font - size:10pt;\">Mystic is a tool that is used to visualize the recorded "
                                                                         "results of an AFSIM simulation event pipe. It reads in AFSIM event recordings (AER) files "
                                                                         "generated by the simulation and displays them in a geographic context.</p>"));
   mUi.appIcon->setPixmap(QPixmap(":/images/Splash_AFSIM_Mystic_BW_SM.png"));
   mUi.buttonBox->button(QDialogButtonBox::Ok)->setText(QCoreApplication::translate("rv::StartupDialog", "Open"));
}

bool rv::StartupDialog::ValidateSelection()
{
   // Check to see if file was found
   QFileInfo info(mSelection);
   if (!info.exists())
   {
      QMessageBox::warning(this,
                           QCoreApplication::translate("rv::StartupDialog", "File Not Found"), // 二次开发（i18n）：接入翻译通道
                           QCoreApplication::translate("rv::StartupDialog", "File: %1 was not found.").arg(mSelection)); // 二次开发（i18n）：参数化翻译
      return false;
   }
   return true;
}

QString rv::StartupDialog::ParseDroppedUrls(const QList<QUrl>& urls) const
{
   return urls.front().toLocalFile();
}
